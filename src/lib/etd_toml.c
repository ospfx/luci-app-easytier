/*
 * etd_toml.c - /etc/easytier/config.toml 生成与解析
 *
 * 生成结果以 root/etc/easytier/config.toml 模板为骨架，再把当前 UCI 配置
 * 填进去；键名与 init.d check_config()（第 154~168 行）grep 的键保持一致：
 *   instance_name / listeners = [] / "tcp://0.0.0.0:PORT" / dev_name /
 *   [[proxy_network]] / wireguard_listen / socks5_proxy
 *
 * 注意：dev_name 与 mtu 放在 [flags] 表里（EasyTier 把命令行同名参数映射到
 * 配置文件时使用的表）。若目标 core 版本不接受这两个键，--check-config 会
 * 报错，需要按 core 版本调整——这是本模块唯一无法用源码验证的映射（见报告）。
 */
#include "etd_cfg.h"

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* 模板里的默认实例 UUID（机器未生成过 et_machine_id 时使用） */
#define ET_TOML_DEF_UUID "f9f05421-7c6b-47d6-a67d-4d58d49f51d8"

/* ---------------- 输出辅助 ---------------- */

/* TOML 基本字符串（转义 " 与 \） */
static void toml_str(et_buf *b, const char *s)
{
	et_buf_addc(b, '"');
	for (const char *p = s ? s : ""; *p; p++) {
		switch (*p) {
		case '"': et_buf_add(b, "\\\""); break;
		case '\\': et_buf_add(b, "\\\\"); break;
		case '\n': et_buf_add(b, "\\n"); break;
		case '\t': et_buf_add(b, "\\t"); break;
		case '\r': break;
		default: et_buf_addc(b, *p); break;
		}
	}
	et_buf_addc(b, '"');
}

static void toml_kv_str(et_buf *b, const char *key, const char *val)
{
	et_buf_add(b, key);
	et_buf_add(b, " = ");
	toml_str(b, val);
	et_buf_addc(b, '\n');
}

/* 数组：每个元素一行，便于人工核对 */
static void toml_kv_array(et_buf *b, const char *key, const et_list *l)
{
	if (!l || l->n == 0) {
		et_buf_addf(b, "%s = []\n", key);
		return;
	}
	et_buf_addf(b, "%s = [\n", key);
	for (size_t i = 0; i < l->n; i++) {
		et_buf_add(b, "\t");
		toml_str(b, l->v[i]);
		et_buf_add(b, i + 1 < l->n ? ",\n" : "\n");
	}
	et_buf_add(b, "]\n");
}

/* ---------------- 实例 ID ---------------- */

static char *instance_uuid(void)
{
	char *s = et_read_file(ET_FILE_MACHINE_ID, NULL);

	if (s) {
		char *w = s;

		/* 去掉空格与换行（原实现是 tr -d ' \n'） */
		for (char *p = s; *p; p++) {
			if (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')
				continue;
			*w++ = *p;
		}
		*w = '\0';
		if (*s)
			return s;
		free(s);
	}
	return strdup(ET_TOML_DEF_UUID);
}

/* ---------------- 生成 ---------------- */

char *et_toml_render(et_cfg *c)
{
	static const char *const schemes[] = { "ws", "wss", "wg", "quic" };
	static const char *const ports[] = { "ws_port", "wss_port", "wg_port", "quic_port" };
	et_buf b;
	char *uuid;
	const char *v;

	et_buf_init(&b);
	if (!c)
		return NULL;

	uuid = instance_uuid();

	et_buf_add(&b, "# Generated by easytierd from /etc/config/easytier, do not edit by hand\n");

	/* ---- 基础字段 ---- */
	v = et_cfg_str(c, "instance_name");
	toml_kv_str(&b, "instance_name", (v && *v) ? v : "default");
	toml_kv_str(&b, "instance_id", uuid ? uuid : ET_TOML_DEF_UUID);
	free(uuid);

	et_buf_addf(&b, "dhcp = %s\n", et_cfg_is01(c, "ip_dhcp") ? "true" : "false");

	v = et_cfg_str(c, "ipaddr");
	if (v && *v)
		toml_kv_str(&b, "ipv4", v);
	v = et_cfg_str(c, "ip6addr");
	if (v && *v)
		toml_kv_str(&b, "ipv6", v);

	/* ---- listeners ----
	 * listenermode != ON 时必须输出字面量 `listeners = []`
	 * （check_config 用 `grep -F 'listeners = []'` 反推 listenermode） */
	v = et_cfg_str(c, "listenermode");
	if (v && strcmp(v, "ON") == 0) {
		et_buf l;
		const char *tcp = et_cfg_str(c, "tcp_port");

		et_buf_init(&l);
		if (tcp && *tcp) {
			et_buf_addf(&l, "\t\"tcp://0.0.0.0:%s\",\n", tcp);
			et_buf_addf(&l, "\t\"udp://0.0.0.0:%s\",\n", tcp);
		}
		for (size_t i = 0; i < sizeof(ports) / sizeof(ports[0]); i++) {
			const char *p = et_cfg_str(c, ports[i]);

			if (p && *p)
				et_buf_addf(&l, "\t\"%s://0.0.0.0:%s\",\n", schemes[i], p);
		}
		if (l.len) {
			et_buf_add(&b, "listeners = [\n");
			et_buf_addn(&b, l.p, l.len);
			et_buf_add(&b, "]\n");
		} else {
			et_buf_add(&b, "listeners = []\n");
		}
		et_buf_free(&l);
	} else {
		et_buf_add(&b, "listeners = []\n");
	}

	toml_kv_array(&b, "exit_nodes", et_cfg_list(c, "exit_nodes"));

	/* 顶层 rpc_portal（模板保留该行；core 会静默忽略，RPC 端口实际走命令行 -r） */
	v = et_cfg_str(c, "rpc_portal");
	if (v && *v) {
		et_buf portal;

		et_buf_init(&portal);
		if (strchr(v, ':'))
			et_buf_add(&portal, v);
		else
			et_buf_addf(&portal, "0.0.0.0:%s", v);
		toml_kv_str(&b, "rpc_portal", portal.p);
		et_buf_free(&portal);
	}

	v = et_cfg_str(c, "socks_port");
	if (v && *v) {
		et_buf s5;

		et_buf_init(&s5);
		et_buf_addf(&s5, "socks5://0.0.0.0:%s", v);
		toml_kv_str(&b, "socks5_proxy", s5.p);
		et_buf_free(&s5);
	}

	/* ---- 网络身份 ---- */
	et_buf_add(&b, "\n[network_identity]\n");
	v = et_cfg_str(c, "network_name");
	toml_kv_str(&b, "network_name", v ? v : "");
	v = et_cfg_str(c, "network_secret");
	toml_kv_str(&b, "network_secret", v ? v : "");

	/* ---- 对端节点 ---- */
	const et_list *peers = et_cfg_list(c, "peeradd");
	for (size_t i = 0; peers && i < peers->n; i++) {
		et_buf_add(&b, "\n[[peer]]\n");
		toml_kv_str(&b, "uri", peers->v[i]);
	}

	/* ---- 子网代理 ---- */
	const et_list *proxy = et_cfg_list(c, "proxy_network");
	for (size_t i = 0; proxy && i < proxy->n; i++) {
		et_buf_add(&b, "\n[[proxy_network]]\n");
		toml_kv_str(&b, "cidr", proxy->v[i]);
	}

	/* ---- 设备参数 ---- */
	v = et_cfg_str(c, "tunname");
	const char *mtu = et_cfg_str(c, "mtu");
	if ((v && *v) || (mtu && *mtu)) {
		et_buf_add(&b, "\n[flags]\n");
		if (v && *v)
			toml_kv_str(&b, "dev_name", v);
		if (mtu && *mtu)
			et_buf_addf(&b, "mtu = %s\n", mtu);
	}

	/* ---- VPN 门户（2.7.0 写法：仅 wg://主机:端口 + 私钥） ---- */
	v = et_cfg_str(c, "vpn_portal");
	const char *key = et_cfg_str(c, "vpn_portal_private_key");
	if (v && et_starts_with(v, "wg://") && !strchr(v + 5, '/') && key && *key) {
		et_buf_add(&b, "\n[vpn_portal_config]\n");
		et_buf_add(&b, "enabled = true\n");
		toml_kv_str(&b, "wireguard_listen", v + 5);
		toml_kv_str(&b, "wireguard_private_key", key);

		const et_list *cl = et_cfg_list(c, "vpn_portal_clients");
		for (size_t i = 0; cl && i < cl->n; i++) {
			const char *eq = strchr(cl->v[i], '=');

			if (!eq || eq == cl->v[i])
				continue;
			char *name = strndup(cl->v[i], (size_t)(eq - cl->v[i]));

			if (!name)
				continue;
			et_buf_add(&b, "\n[[vpn_portal_config.clients]]\n");
			toml_kv_str(&b, "name", name);
			toml_kv_str(&b, "virtual_ip", eq + 1);
			et_buf_add(&b, "groups = []\n");
			free(name);
		}
	} else if (v && *v) {
		et_buf_add(&b, "\n# vpn_portal 不是 2.7.0 可用的 wg://主机:端口（或缺少私钥），已跳过\n");
	}

	if (!b.p)
		et_buf_add(&b, "");
	return et_buf_steal(&b);
}

/* ---------------- 解析 ---------------- */

static const char *skip_ws(const char *p)
{
	while (*p == ' ' || *p == '\t')
		p++;
	return p;
}

/* 取一行的值部分：去首尾空白、外层引号与行尾注释；返回 malloc 串 */
static char *toml_value(const char *val, size_t len)
{
	while (len > 0 && isspace((unsigned char)val[len - 1]))
		len--;
	if (len == 0)
		return NULL;

	if (val[0] == '"' || val[0] == '\'') {
		char q = val[0];
		size_t i = 1;

		while (i < len && val[i] != q)
			i++;
		return strndup(val + 1, i > 1 ? i - 1 : 0);
	}

	size_t n = 0;
	while (n < len && val[n] != '#')
		n++;
	while (n > 0 && isspace((unsigned char)val[n - 1]))
		n--;
	if (n == 0)
		return NULL;
	return strndup(val, n);
}

/* 两轮查找：先只匹配顶层键（第一个 [section] 之前），找不到再全文匹配 */
char *et_toml_get(const char *content, const char *key)
{
	size_t klen;

	if (!content || !key || !*key)
		return NULL;
	klen = strlen(key);

	for (int pass = 0; pass < 2; pass++) {
		const char *p = content;
		bool in_section = false;

		while (*p) {
			const char *eol = strchr(p, '\n');
			size_t len = eol ? (size_t)(eol - p) : strlen(p);
			const char *line = skip_ws(p);
			size_t llen = (size_t)(p + len - line);

			if (llen > 0 && line[0] == '[')
				in_section = true;

			if ((!in_section || pass == 1) && llen > klen &&
			    strncmp(line, key, klen) == 0) {
				const char *q = skip_ws(line + klen);

				if (*q == '=') {
					q = skip_ws(q + 1);
					char *val = toml_value(q, (size_t)(p + len - q));

					if (val)
						return val;
				}
			}
			if (!eol)
				break;
			p = eol + 1;
		}
	}
	return NULL;
}

char *et_toml_port(const char *content, const char *scheme)
{
	char needle[32];
	size_t nlen;
	const char *p;

	if (!content || !scheme || !*scheme)
		return NULL;
	nlen = (size_t)snprintf(needle, sizeof(needle), "\"%s://", scheme);
	if (nlen >= sizeof(needle))
		return NULL;

	p = content;
	while ((p = strstr(p, needle)) != NULL) {
		const char *host = p + nlen;
		const char *end = strchr(host, '"');

		if (!end)
			break;
		const char *colon = NULL;
		for (const char *q = host; q < end; q++)
			if (*q == ':')
				colon = q;
		if (colon) {
			const char *d = colon + 1;
			const char *e = d;

			while (e < end && isdigit((unsigned char)*e))
				e++;
			if (e > d && e == end)
				return strndup(d, (size_t)(e - d));
		}
		p = host;
	}
	return NULL;
}
